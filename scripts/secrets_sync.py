def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="secrets-sync",
        description="Sync ~/.secrets with a folder in your personal Bitwarden vault.",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("init", help="tag this machine (writes ~/.config/secrets-sync/config.toml)")
    p.add_argument("--machine", required=True, help="this machine's tag, for example mac or bigboss")
    p.add_argument("--force", action="store_true", help="replace an existing config")
    p.set_defaults(func=cmd_init)

    p = sub.add_parser("check", help="compare ~/.secrets with Bitwarden by name; exit 1 on drift")
    p.add_argument("--non-interactive", action="store_true", help="use BW_SESSION and never prompt")
    p.set_defaults(func=cmd_check)

    p = sub.add_parser("pull", help="write ~/.secrets from Bitwarden for this machine")
    p.add_argument("--dry-run", action="store_true", help="show which names would change")
    p.add_argument("--keep-unmanaged", action="store_true",
                   help="move entries Bitwarden does not know into the local-only block")
    p.add_argument("--force", action="store_true", help="drop entries Bitwarden does not know")
    p.add_argument("--non-interactive", action="store_true", help="use BW_SESSION and never prompt")
    p.set_defaults(func=cmd_pull)

    p = sub.add_parser("push", help="copy named variables from ~/.secrets into one Bitwarden item")
    p.add_argument("--item", required=True, help="Bitwarden item name, for example livekit")
    p.add_argument("--machines", required=True, help="all, or a comma list of machine tags")
    p.add_argument("--force", action="store_true", help="overwrite existing fields or retag the item")
    p.add_argument("names", nargs="+", metavar="NAME")
    p.set_defaults(func=cmd_push)

    p = sub.add_parser("import", help="push many variables following a TOML plan of names")
    p.add_argument("plan", help="TOML file: [item] machines = \"all\", vars = [\"NAME\", ...]")
    p.add_argument("--force", action="store_true", help="overwrite existing fields or retag items")
    p.set_defaults(func=cmd_import)

    p = sub.add_parser("doctor", help="report risky states; never unlocks the vault")
    p.set_defaults(func=cmd_doctor)
    return parser


def raise_system_exit(signum: int, _frame: object) -> None:
    raise SystemExit(128 + signum)


def main(argv: list[str] | None = None) -> int:
    os.umask(0o077)
    with contextlib.suppress(ImportError, ValueError, OSError):
        import resource
        resource.setrlimit(resource.RLIMIT_CORE, (0, 0))  # no core dump with secrets in it
    previous_hook = sys.excepthook
    sys.excepthook = report_exception
    previous = {s: signal.signal(s, raise_system_exit) for s in (signal.SIGTERM, signal.SIGHUP)}
    try:
        args = build_parser().parse_args(argv)
        return args.func(args, Paths.from_env())
    except (Exception, KeyboardInterrupt) as exc:
        report_exception(type(exc), exc, exc.__traceback__)
        return 130 if isinstance(exc, KeyboardInterrupt) else 2
    finally:
        for s, handler in previous.items():
            signal.signal(s, handler)
        sys.excepthook = previous_hook


if __name__ == "__main__":
    sys.exit(main())
