class SecretsSyncError(Exception):
    """An expected failure. Its message is printed, so it must never hold a secret value."""


class BwError(SecretsSyncError):
    pass


# ---------------------------------------------------------------------------
# Redaction: every value read from the vault or ~/.secrets is registered here, and all
# output goes through it as a second line of defense.


class Redactor:
    MIN_LENGTH = 4

    def __init__(self) -> None:
        self._values: set[str] = set()

    def add(self, value: str | None) -> None:
        if value and len(value) >= self.MIN_LENGTH:
            self._values.add(value)
            self._values.add(json.dumps(value)[1:-1])  # the form it takes inside bw's JSON

    def __call__(self, text: str) -> str:
        for value in sorted(self._values, key=len, reverse=True):
            if value in text:
                text = text.replace(value, "[REDACTED]")
        return text


REDACT = Redactor()


def out(message: str = "") -> None:
    print(REDACT(message), file=sys.stdout, flush=True)


def err(message: str) -> None:
    print(REDACT(message), file=sys.stderr, flush=True)


def report_exception(exc_type: type[BaseException], exc: BaseException, tb: object) -> None:
    """Print an exception without its traceback locals or, for unexpected errors, its message,
    which could quote a value (for example a parse error that echoes its input)."""
    if issubclass(exc_type, KeyboardInterrupt):
        err("secrets-sync: interrupted")
    elif isinstance(exc, SecretsSyncError):
        err(f"secrets-sync: error: {exc}")
    elif isinstance(exc, OSError) and exc.strerror:
        err(f"secrets-sync: error: {exc.strerror}" + (f": {exc.filename}" if exc.filename else ""))
    else:
        err(f"secrets-sync: internal error ({exc_type.__name__}). "
            "Rerun with SECRETS_SYNC_DEBUG=1 for a redacted traceback.")
        if os.environ.get("SECRETS_SYNC_DEBUG") == "1":
            err("".join(traceback.format_exception(exc_type, exc, tb)))  # type: ignore[arg-type]


