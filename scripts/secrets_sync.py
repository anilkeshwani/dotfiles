class Doctor:
    def __init__(self) -> None:
        self.problems = 0

    def ok(self, msg: str) -> None:
        out(f"ok    {msg}")

    def warn(self, msg: str) -> None:
        self.problems += 1
        out(f"WARN  {msg}")

    def info(self, msg: str) -> None:
        out(f"info  {msg}")


def history_findings(paths: Paths) -> list[str]:
    risky = [
        (re.compile(r"BW_SESSION=\S"), "a BW_SESSION value"),
        (re.compile(r"BW_PASSWORD=\S"), "a BW_PASSWORD value"),
        (re.compile(r"\bbw\s+unlock\s+(?:--\S+\s+)*[^-\s]"), "a password passed to bw unlock"),
        (re.compile(r"\bbw\s+login\s+\S+\s+[^-\s]"), "a password passed to bw login"),
    ]
    files = {paths.home / ".zsh_history", paths.home / ".bash_history"}
    if os.environ.get("HISTFILE"):
        files.add(Path(os.environ["HISTFILE"]))
    findings = []
    for file in sorted(files):
        with contextlib.suppress(OSError):
            text = file.read_text(errors="replace")
            for pattern, what in risky:
                count = len(pattern.findall(text))
                if count:
                    findings.append(f"{file} holds {count} line(s) with {what}; delete them")
    return findings


def git_ignores(repo_dir: Path, rel: str) -> bool | None:
    try:
        top = subprocess.run(["git", "-C", str(repo_dir), "rev-parse", "--show-toplevel"],
                             capture_output=True, text=True, stdin=subprocess.DEVNULL, timeout=20)
        if top.returncode != 0:
            return None
        res = subprocess.run(["git", "-C", str(repo_dir), "check-ignore", "-q", "--no-index", rel],
                             capture_output=True, stdin=subprocess.DEVNULL, timeout=20)
    except (OSError, subprocess.SubprocessError):
        return None
    return res.returncode == 0


def cmd_doctor(args: argparse.Namespace, paths: Paths) -> int:
    doc = Doctor()
    exe = shutil.which("bw")
    if not exe:
        doc.warn("bw is not installed (see docs/secrets-sync.md)")
    else:
        try:
            version = Bitwarden(exe).run(["--version"]).strip()
            year = int(version.split(".")[0])
            if year < datetime.now().year - BW_OLDEST_OK_YEAR_LAG:
                doc.warn(f"bw {version} is old; upgrade it")
            else:
                doc.ok(f"bw {version} at {exe}")
        except (SecretsSyncError, ValueError, IndexError):
            doc.warn("could not read the bw version")
        try:
            status = Bitwarden(exe).status()
            state = status["status"]
            if state == "unauthenticated":
                doc.warn("bw is not logged in (run `bw login` yourself)")
            elif state == "unlocked":
                doc.warn("the vault is unlocked; run `bw lock` when you are done")
            else:
                doc.ok("bw is logged in and the vault is locked")
            last = status.get("lastSync")
            if isinstance(last, str):
                age = datetime.now(timezone.utc) - datetime.fromisoformat(last.replace("Z", "+00:00"))
                hours = age.total_seconds() / 3600
                (doc.warn if hours > SYNC_STALE_HOURS else doc.ok)(f"last bw sync {hours:.0f} hours ago")
        except (SecretsSyncError, ValueError):
            doc.warn("could not read `bw status`")
    if os.environ.get("BW_SESSION"):
        doc.warn("BW_SESSION is set in this shell; unset it and run `bw lock` when done")

    try:
        config = load_config(paths)
        doc.ok(f"machine tag {config.machine!r} from {paths.config}")
    except SecretsSyncError as exc:
        doc.warn(str(exc))

    try:
        st = os.lstat(paths.secrets)
        if stat.S_ISLNK(st.st_mode):
            doc.warn(f"{paths.secrets} is a symlink")
        elif stat.S_IMODE(st.st_mode) != 0o600:
            doc.warn(f"{paths.secrets} has mode {stat.S_IMODE(st.st_mode):o}; run chmod 600 {paths.secrets}")
        else:
            doc.ok(f"{paths.secrets} is mode 600")
        _, parsed = load_local(paths)
        doc.info(f"{paths.secrets}: {'generated by pull' if parsed.generated else 'written by hand'}, "
                 f"{len(parsed.assignments)} managed and {len(parsed.local_assignments)} local-only variables")
    except FileNotFoundError:
        doc.info(f"{paths.secrets} does not exist yet")
    except SecretsSyncError as exc:
        doc.warn(str(exc))
    try:
        ensure_safe_dir(paths.secrets.parent)
        doc.ok(f"{paths.secrets.parent} is not writable by group or others")
    except SecretsSyncError as exc:
        doc.warn(str(exc))

    if paths.backups.exists():
        st = os.lstat(paths.backups)
        if stat.S_ISLNK(st.st_mode) or stat.S_IMODE(st.st_mode) != 0o700:
            doc.warn(f"{paths.backups} should be a mode 700 directory")
        loose = [p.name for p in paths.backups.iterdir() if stat.S_IMODE(p.lstat().st_mode) != 0o600]
        if loose:
            doc.warn(f"backups not mode 600: {', '.join(sorted(loose))}")
        else:
            doc.ok(f"{len(list(paths.backups.iterdir()))} backups in {paths.backups}, all mode 600")

    home_repo = git_ignores(paths.home, ".secrets")
    if home_repo is False:
        doc.warn(f"{paths.home} is inside a git repository that does not ignore .secrets")
    elif home_repo is True:
        doc.ok(f"the git repository around {paths.home} ignores .secrets")
    dotfiles = Path(__file__).resolve().parent.parent
    for rel in (".secrets", "home/.secrets"):
        if git_ignores(dotfiles, rel) is False:
            doc.warn(f"the dotfiles repo does not ignore {rel}")
    hooks_path = subprocess.run(["git", "-C", str(dotfiles), "config", "core.hooksPath"],
                                capture_output=True, text=True, stdin=subprocess.DEVNULL).stdout.strip()
    hook_dirs = {(dotfiles / "home/.config/git/hooks").resolve(), (paths.home / ".config/git/hooks").resolve()}
    if hooks_path and (dotfiles / Path(hooks_path).expanduser()).resolve() in hook_dirs:
        doc.ok(f"dotfiles repo commits go through the hooks in {hooks_path}")
    else:
        doc.warn("the pre-commit secrets guard is not enabled for the dotfiles repo (see docs/secrets-sync.md)")

    sourced = []
    for rc in (".zshrc", ".bashrc"):
        with contextlib.suppress(OSError):
            text = (paths.home / rc).read_text()
            if re.search(r"^[^#]*\.\s+\"?\$\{?HOME\}?/\.secrets|^[^#]*source\s+\S*\.secrets", text, re.M):
                sourced.append(rc)
    (doc.ok if sourced else doc.warn)(f"shell rc files that source ~/.secrets: {', '.join(sourced) or 'none'}")

    for finding in history_findings(paths):
        doc.warn(finding)
    with contextlib.suppress(OSError, subprocess.SubprocessError):
        crontab = subprocess.run(["crontab", "-l"], capture_output=True, text=True,
                                 stdin=subprocess.DEVNULL, timeout=10).stdout
        if "secrets-sync" in crontab:
            doc.warn("a crontab entry runs secrets-sync; it is meant to run by hand")

    out(f"{doc.problems} warning(s)")
    return 1 if doc.problems else 0


