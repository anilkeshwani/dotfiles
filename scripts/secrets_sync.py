def push_groups(groups: list[PushGroup], args: argparse.Namespace, paths: Paths) -> int:
    config = load_config(paths)
    if not stdio_is_tty():
        raise SecretsSyncError("push and import ask for confirmation, so they need a terminal")
    _, parsed = load_local(paths)
    local = parsed.managed_map()
    local_only = parsed.local_names()

    seen: set[str] = set()
    for group in groups:
        parse_machines(group.machines, group.item)
        if not group.item.strip() or not group.item.isprintable():
            raise SecretsSyncError("item names must be printable and non-empty")
        for name in group.names:
            if name in seen:
                raise SecretsSyncError(f"{name} is listed twice")
            seen.add(name)
            if not NAME_RE.match(name) or is_denied_name(name) or name == MACHINES_FIELD:
                raise SecretsSyncError(f"refusing to push {name!r}")
            if name in local_only:
                raise SecretsSyncError(f"{name} is in the local-only block; move it out first if it should be shared")
            if name not in local:
                raise SecretsSyncError(f"{name} is not in {paths.secrets}")
            value = local[name].value
            if value is None:
                raise SecretsSyncError(f"{name} needs a shell to evaluate ($, backticks); set a literal value first")
            check_value(name, value)

    pushed: list[str] = []
    with vault_session(interactive=True) as bw:
        folder_id = find_folder(bw, config.folder)
        if folder_id is None:
            if not confirm(f"Create folder {config.folder!r} in your personal vault?"):
                raise SecretsSyncError("aborted")
            folder_id = bw.create("folder", {"name": config.folder})["id"]
        items = bw.list_items(folder_id)
        field_owner = {
            f.get("name"): it.get("name")
            for it in items for f in (it.get("fields") or []) if isinstance(f, dict) and f.get("name") != MACHINES_FIELD
        }
        for group in groups:
            pushed += push_one_group(bw, folder_id, items, field_owner, group, local, args.force)
    out(f"Pushed: {names_line(pushed)}")
    if pushed:
        out("Review the items in the Bitwarden app, then run secrets-sync check.")
    return 0


def push_one_group(bw: Bitwarden, folder_id: str, items: list[dict], field_owner: dict,
                   group: PushGroup, local: dict[str, Assignment], force: bool) -> list[str]:
    same_name = [it for it in items if it.get("name") == group.item]
    if len(same_name) > 1:
        raise SecretsSyncError(f"more than one item is named {group.item!r}; rename one")
    existing = same_name[0] if same_name else None
    if existing and existing.get("organizationId"):
        raise SecretsSyncError(f"item {group.item!r} belongs to an organization; refusing to write to it")
    for name in group.names:
        owner = field_owner.get(name)
        if owner is not None and owner != group.item:
            raise SecretsSyncError(f"{name} already lives in item {owner!r}; push it there or remove it first")

    by_name = {f.get("name"): f for f in (existing or {}).get("fields") or [] if isinstance(f, dict)}
    current_machines = by_name.get(MACHINES_FIELD, {}).get("value")
    if existing and current_machines and current_machines != group.machines and not force:
        raise SecretsSyncError(
            f"item {group.item!r} is tagged {current_machines!r}, not {group.machines!r}; pass --force to retag it"
        )
    add, overwrite, unchanged = [], [], []
    for name in group.names:
        value = local[name].value
        if name not in by_name:
            add.append(name)
        elif by_name[name].get("value") == value:
            unchanged.append(name)
        elif force:
            overwrite.append(name)
        else:
            raise SecretsSyncError(f"{name} already exists in {group.item!r} with another value; pass --force to overwrite")
    if not add and not overwrite and (not existing or current_machines == group.machines):
        out(f"Item {group.item!r}: nothing to do ({names_line(unchanged)} unchanged)")
        return []
    out(f"Item {group.item!r} ({'existing' if existing else 'new'}, machines: {group.machines})")
    out(f"  add:       {names_line(add)}")
    out(f"  overwrite: {names_line(overwrite)}")
    out(f"  unchanged: {names_line(unchanged)}")
    if not confirm(f"Write item {group.item!r}?"):
        out("  skipped")
        return []

    def apply(fields: list) -> list:
        """Apply the confirmed changes to a field list, matching fields by name."""
        fields = [dict(f) for f in fields if isinstance(f, dict)]
        index = {f.get("name"): f for f in fields}
        for name in add + overwrite:
            if name in index:
                index[name].update(value=local[name].value, type=1)
            else:
                fields.append({"name": name, "value": local[name].value, "type": 1, "linkedId": None})
        if MACHINES_FIELD in index:
            index[MACHINES_FIELD]["value"] = group.machines
        else:
            fields.append({"name": MACHINES_FIELD, "value": group.machines, "type": 0, "linkedId": None})
        return fields

    if existing:
        # Edit the item as it is on the server now, so a field added since the listing is kept.
        fresh = bw.get_item(existing["id"])
        if fresh.get("organizationId"):
            raise SecretsSyncError(f"item {group.item!r} belongs to an organization; refusing to write to it")
        fresh["fields"] = apply(fresh.get("fields") or [])
        bw.edit_item(existing["id"], fresh)
    else:
        created = bw.create("item", {
            "organizationId": None, "collectionIds": None, "folderId": folder_id,
            "type": 2, "name": group.item, "favorite": False, "reprompt": 0,
            "notes": "Managed by secrets-sync. Hidden fields are environment variables; "
                     "the machines field lists the hosts that receive them (all, or tags such as mac, bigboss).",
            "secureNote": {"type": 0}, "fields": apply([]),
            "login": None, "card": None, "identity": None,
        })
        items.append(created)
    for name in add + overwrite:
        field_owner[name] = group.item
    return add + overwrite


