# Paths and configuration


@dataclass(frozen=True)
class Paths:
    home: Path
    secrets: Path
    config: Path
    state: Path
    backups: Path

    @classmethod
    def from_env(cls) -> Paths:
        home = Path.home()
        config_root = Path(os.environ.get("XDG_CONFIG_HOME") or home / ".config")
        state_root = Path(os.environ.get("XDG_STATE_HOME") or home / ".local" / "state")
        state = state_root / "secrets-sync"
        return cls(
            home=home,
            secrets=home / ".secrets",
            config=config_root / "secrets-sync" / "config.toml",
            state=state,
            backups=state / "backups",
        )


@dataclass(frozen=True)
class Config:
    machine: str
    machine_id: str
    folder: str
    backup_count: int


def machine_fingerprint() -> str:
    """A stable per-machine id, hashed. Ties the config file to the machine it was made on, so
    a copied config cannot make another host pull this host's secrets."""
    raw = ""
    for candidate in ("/etc/machine-id", "/var/lib/dbus/machine-id"):
        with contextlib.suppress(OSError):
            raw = Path(candidate).read_text().strip()
            if raw:
                break
    if not raw and sys.platform == "darwin":
        with contextlib.suppress(OSError, subprocess.SubprocessError):
            ioreg = subprocess.run(
                ["/usr/sbin/ioreg", "-rd1", "-c", "IOPlatformExpertDevice"],
                capture_output=True, text=True, timeout=10, stdin=subprocess.DEVNULL,
            ).stdout
            match = re.search(r'"IOPlatformUUID"\s*=\s*"([^"]+)"', ioreg)
            raw = match.group(1) if match else ""
    if not raw:
        raw = "hostname:" + socket.gethostname()
    return hashlib.sha256(("secrets-sync:" + raw).encode()).hexdigest()[:16]


def validate_tag(tag: str, what: str) -> str:
    if not TAG_RE.match(tag):
        raise SecretsSyncError(f"{what} {tag!r} is not a valid machine tag (use lowercase letters, digits and -)")
    return tag


def load_config(paths: Paths) -> Config:
    path = paths.config
    try:
        st = os.lstat(path)
    except FileNotFoundError:
        raise SecretsSyncError(
            f"no config at {path}. Tag this machine first: secrets-sync init --machine <tag>"
        ) from None
    if stat.S_ISLNK(st.st_mode) or not stat.S_ISREG(st.st_mode):
        raise SecretsSyncError(f"{path} must be a regular file, not a symlink")
    if st.st_uid != os.getuid() or st.st_mode & 0o022:
        raise SecretsSyncError(f"{path} must be owned by you and not writable by group or others")
    try:
        data = tomllib.loads(path.read_text())
    except tomllib.TOMLDecodeError as exc:
        raise SecretsSyncError(f"{path} is not valid TOML: {exc}") from None
    machine = data.get("machine")
    if not isinstance(machine, str) or not machine:
        raise SecretsSyncError(f"{path} has no machine = \"<tag>\" entry")
    validate_tag(machine, "machine")
    if machine == ALL_MACHINES:
        raise SecretsSyncError(f"{ALL_MACHINES!r} is reserved; tag this machine with its own name")
    machine_id = data.get("machine_id")
    if machine_id != machine_fingerprint():
        raise SecretsSyncError(
            f"{path} was made on another machine (machine_id does not match this one). "
            "Run secrets-sync init --machine <tag> --force on this machine."
        )
    folder = data.get("folder", DEFAULT_FOLDER)
    backup_count = data.get("backups", DEFAULT_BACKUP_COUNT)
    if not isinstance(folder, str) or not folder:
        raise SecretsSyncError(f"{path}: folder must be a non-empty string")
    if not isinstance(backup_count, int) or not 1 <= backup_count <= 100:
        raise SecretsSyncError(f"{path}: backups must be an integer from 1 to 100")
    return Config(machine=machine, machine_id=machine_id, folder=folder, backup_count=backup_count)


# ---------------------------------------------------------------------------
# Parsing ~/.secrets. The file is never executed: values are read with a small parser for
# the shell quoting forms people write by hand, and anything that would need a shell to
# evaluate ($VAR, $(...), backticks) is reported as dynamic.


@dataclass
class Assignment:
    name: str
    value: str | None  # None when the value needs a shell to evaluate
    lineno: int
    raw: str


@dataclass
class ParsedSecrets:
    generated: bool = False
    assignments: list[Assignment] = field(default_factory=list)  # outside the local block
    local_assignments: list[Assignment] = field(default_factory=list)
    local_lines: list[str] = field(default_factory=list)  # verbatim, without markers
    other_lines: list[int] = field(default_factory=list)  # line numbers of non-assignments

    def managed_map(self) -> dict[str, Assignment]:
        return {a.name: a for a in self.assignments}  # the shell keeps the last assignment

    def local_names(self) -> set[str]:
        return {a.name for a in self.local_assignments}


def parse_shell_value(text: str) -> tuple[str | None, bool]:
    """Parse the right-hand side of NAME=... Returns (value, ok). value is None for a dynamic
    value; ok is False when the line is not a simple assignment (unterminated quote,
    trailing command)."""
    out_chars: list[str] = []
    i, n = 0, len(text)
    dynamic = False
    while i < n:
        c = text[i]
        if c in " \t":
            break
        if c == "'":
            end = text.find("'", i + 1)
            if end == -1:
                return None, False
            out_chars.append(text[i + 1:end])
            i = end + 1
        elif c == '"':
            i += 1
            while True:
                if i >= n:
                    return None, False
                d = text[i]
                if d == '"':
                    i += 1
                    break
                if d == "\\" and i + 1 < n and text[i + 1] in '"\\$`':
                    out_chars.append(text[i + 1])
                    i += 2
                    continue
                if d in "$`":
                    dynamic = True
                out_chars.append(d)
                i += 1
        elif c == "\\":
            if i + 1 >= n:
                return None, False
            out_chars.append(text[i + 1])
            i += 2
        elif c in "$`~{*?[" or (c == "=" and i == 0):
            # Unquoted, these expand: parameters, commands, tildes, braces, globs and
            # zsh's =command. Report the value as dynamic.
            dynamic = True
            out_chars.append(c)
            i += 1
        elif c in ";&|<>()":
            return None, False
        else:
            out_chars.append(c)
            i += 1
    rest = text[i:].strip()
    if rest and not rest.startswith("#"):
        return None, False
    return (None if dynamic else "".join(out_chars)), True


def parse_secrets(text: str) -> ParsedSecrets:
    parsed = ParsedSecrets()
    lines = text.split("\n")  # not splitlines(): U+2028 and friends are not line breaks to a shell
    parsed.generated = bool(lines) and lines[0] == HEADER_FIRST_LINE
    in_local = False
    for lineno, line in enumerate(lines, start=1):
        stripped = line.strip()
        if stripped == LOCAL_BEGIN:
            in_local = True
            continue
        if stripped == LOCAL_END:
            in_local = False
            continue
        if in_local:
            if line != LOCAL_HINT:
                parsed.local_lines.append(line)
        if not stripped or stripped.startswith("#"):
            continue
        match = ASSIGNMENT_RE.match(line)
        value, ok = parse_shell_value(match.group(3)) if match else (None, False)
        if not match or not ok:
            if not in_local:
                parsed.other_lines.append(lineno)
            continue
        REDACT.add(value)
        assignment = Assignment(name=match.group(2), value=value, lineno=lineno, raw=line)
        (parsed.local_assignments if in_local else parsed.assignments).append(assignment)
    if in_local:
        raise SecretsSyncError("~/.secrets has a local-only block with no end marker; fix it by hand")
    return parsed


# ---------------------------------------------------------------------------
# Rendering


def is_denied_name(name: str) -> bool:
    return name in DENIED_NAMES or name.startswith(DENIED_PREFIXES) or name.endswith(DENIED_SUFFIXES)


def check_value(name: str, value: str) -> None:
    if not all(c.isprintable() for c in value):
        raise SecretsSyncError(
            f"{name} contains a newline or control character; secrets-sync only handles "
            "single-line values. Store it another way."
        )


def shell_quote(value: str) -> str:
    """Single-quote for sh, bash and zsh: nothing inside single quotes is expanded, and an
    embedded quote is closed, escaped and reopened."""
    return "'" + value.replace("'", "'\\''") + "'"


def printable(text: str) -> str:
    return "".join(c if c.isprintable() else "?" for c in text)


def render_secrets(machine: str, folder: str, groups: dict[str, list[tuple[str, str]]],
                   local_lines: list[str]) -> str:
    lines = [
        HEADER_FIRST_LINE,
        f"# Machine tag: {machine}. Source: Bitwarden folder {printable(folder)!r}.",
        "# Change values in Bitwarden, then run: secrets-sync pull",
    ]
    for item in sorted(groups, key=str.casefold):
        lines.append("")
        lines.append(f"# Bitwarden item: {printable(item)}")
        for name, value in sorted(groups[item]):
            if not NAME_RE.match(name) or is_denied_name(name):
                raise SecretsSyncError(f"refusing to write variable {name!r}")
            check_value(name, value)
            lines.append(f"export {name}={shell_quote(value)}")
    lines += ["", LOCAL_BEGIN, LOCAL_HINT, *local_lines, LOCAL_END]
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Bitwarden CLI


def bw_executable() -> str:
    exe = shutil.which("bw")
    if not exe:
        raise SecretsSyncError("bw is not installed. See docs/secrets-sync.md for the install command.")
    return exe


def child_env(session: str | None) -> dict[str, str]:
    env = {k: v for k, v in os.environ.items() if k in BW_ENV_ALLOW or k.startswith("LC_")}
    if session:
        env["BW_SESSION"] = session
    return env


def parse_json_output(stdout: str, what: str) -> object:
    text = stdout.strip()
    candidates = [text] + [line for line in reversed(text.splitlines()) if line[:1] in "[{"]
    for candidate in candidates:
        with contextlib.suppress(ValueError):
            return json.loads(candidate)
    raise BwError(f"could not read the output of `bw {what}` as JSON; has the bw output format changed?")


class Bitwarden:
    """Runs bw with the session key in the child's environment only, never on its command
    line (other users can read command lines with ps), and never with a terminal on stdin."""

    def __init__(self, exe: str, session: str | None = None) -> None:
        self.exe = exe
        self.session = session

    def run(self, args: list[str], stdin: str | None = None, new_session: bool = False) -> str:
        try:
            proc = subprocess.run(
                [self.exe, "--nointeraction", *args],
                input=stdin if stdin is not None else None,
                stdin=None if stdin is not None else subprocess.DEVNULL,
                capture_output=True, text=True, env=child_env(self.session),
                timeout=BW_TIMEOUT_SECONDS, start_new_session=new_session,
            )
        except subprocess.TimeoutExpired:
            raise BwError(f"`bw {args[0]}` timed out") from None
        if proc.returncode != 0:
            lines = [ln for ln in proc.stderr.splitlines() + proc.stdout.splitlines()
                     if ln.strip() and "ServerConfig" not in ln]
            detail = REDACT(lines[-1].strip())[:200] if lines else "no message"
            raise BwError(f"`bw {args[0]}` failed (exit {proc.returncode}): {detail}")
        return proc.stdout

    def json(self, args: list[str]) -> object:
        return parse_json_output(self.run(args), " ".join(args[:2]))

    def status(self) -> dict:
        data = self.json(["status"])
        if not isinstance(data, dict) or data.get("status") not in ("unauthenticated", "locked", "unlocked"):
            raise BwError("unexpected `bw status` output; has the bw output format changed?")
        return data

    def sync(self) -> None:
        self.run(["sync"])

    def lock(self) -> None:
        # Its own session, so a hangup sent to the terminal's process group cannot kill it.
        self.run(["lock"], new_session=True)

    def list_folders(self) -> list[dict]:
        return expect_list(self.json(["list", "folders"]), "list folders")

    def list_items(self, folder_id: str) -> list[dict]:
        return expect_list(self.json(["list", "items", "--folderid", folder_id]), "list items")

    def get_item(self, item_id: str) -> dict:
        data = self.json(["get", "item", item_id])
        if not isinstance(data, dict):
            raise BwError("unexpected `bw get item` output")
        return data

    def create(self, kind: str, obj: dict) -> dict:
        data = parse_json_output(self.run(["create", kind], stdin=encode(obj)), f"create {kind}")
        if not isinstance(data, dict) or not isinstance(data.get("id"), str):
            raise BwError(f"unexpected `bw create {kind}` output")
        return data

    def edit_item(self, item_id: str, obj: dict) -> None:
        self.run(["edit", "item", item_id], stdin=encode(obj))


def encode(obj: dict) -> str:
    return base64.b64encode(json.dumps(obj).encode()).decode()


def expect_list(data: object, what: str) -> list[dict]:
    if not isinstance(data, list) or not all(isinstance(x, dict) for x in data):
        raise BwError(f"unexpected `bw {what}` output; has the bw output format changed?")
    return data


def stdio_is_tty() -> bool:
    return sys.stdin.isatty() and sys.stdout.isatty()


def require_session_mode(non_interactive: bool) -> bool:
    """Return True when the run may prompt. Refuses to run unattended (cron, pipes) unless
    the caller passed --non-interactive and an unlocked session in BW_SESSION."""
    if non_interactive:
        if not os.environ.get("BW_SESSION"):
            raise SecretsSyncError("--non-interactive needs an unlocked session in BW_SESSION")
        return False
    if not stdio_is_tty():
        raise SecretsSyncError(
            "refusing to run without a terminal on stdin and stdout. Run it by hand "
            "(over ssh use ssh -t), or pass --non-interactive with BW_SESSION set."
        )
    return True


@contextlib.contextmanager
def vault_session(interactive: bool) -> Iterator[Bitwarden]:
    """Yield a Bitwarden client with an unlocked, freshly synced vault. When this run
    unlocked the vault it locks it again on every exit path, including errors and Ctrl-C."""
    exe = bw_executable()
    env_session = os.environ.get("BW_SESSION")
    if env_session:
        REDACT.add(env_session)
        bw = Bitwarden(exe, env_session)
        if bw.status()["status"] != "unlocked":
            raise SecretsSyncError("BW_SESSION is set but does not unlock the vault (expired or stale?)")
        bw.sync()
        yield bw
        return
    if not interactive:
        raise SecretsSyncError("no BW_SESSION and prompting is not allowed")
    status = Bitwarden(exe).status()["status"]
    if status == "unauthenticated":
        raise SecretsSyncError("bw is not logged in. Run `bw login` yourself first.")
    must_lock = True  # set before unlocking so an interrupted unlock is still locked
    try:
        err("secrets-sync: unlocking the Bitwarden vault (bw asks for your master password)")
        proc = subprocess.run(
            [exe, "unlock", "--raw"], stdout=subprocess.PIPE, text=True,
            env=child_env(None), timeout=600,
        )
        session = proc.stdout.strip()
        if proc.returncode != 0 or not session or len(session.split()) != 1:
            raise SecretsSyncError("bw unlock failed")
        REDACT.add(session)
        bw = Bitwarden(exe, session)
        bw.sync()
        yield bw
    finally:
        if must_lock:
            lock_vault(exe)


def lock_vault(exe: str) -> None:
    """Lock the vault. Ctrl-C, SIGTERM and SIGHUP are held back until bw lock has finished,
    so a second signal (an ssh hangup is often sent twice) cannot skip the lock."""
    held = {signal.SIGINT, signal.SIGTERM, signal.SIGHUP}
    signal.pthread_sigmask(signal.SIG_BLOCK, held)
    try:
        Bitwarden(exe).lock()
        err("secrets-sync: vault locked")
    except BaseException:
        err("secrets-sync: WARNING: `bw lock` failed. Run `bw lock` yourself now.")
    finally:
        signal.pthread_sigmask(signal.SIG_UNBLOCK, held)


# ---------------------------------------------------------------------------
# Vault model: one personal folder, one secure note per group, one hidden field per
# variable, and a text field `machines` naming the hosts that receive the item.


@dataclass(frozen=True)
class VaultVar:
    name: str
    value: str
    item: str
    machines: frozenset[str]

    def for_machine(self, machine: str) -> bool:
        return ALL_MACHINES in self.machines or machine in self.machines


def parse_machines(raw: object, item: str) -> frozenset[str]:
    if not isinstance(raw, str) or not raw.strip():
        raise SecretsSyncError(f"item {item!r}: the {MACHINES_FIELD} field is empty")
    tags = frozenset(t.strip().lower() for t in raw.split(","))
    for tag in tags:
        validate_tag(tag, f"item {item!r}: machine tag")
    return tags


def find_folder(bw: Bitwarden, name: str) -> str | None:
    matches = [f for f in bw.list_folders() if f.get("name") == name]
    if len(matches) > 1:
        raise SecretsSyncError(f"more than one Bitwarden folder is named {name!r}; rename one")
    if not matches:
        return None
    folder_id = matches[0].get("id")
    if not isinstance(folder_id, str):
        raise BwError("unexpected `bw list folders` output")
    return folder_id


def load_vault(bw: Bitwarden, folder: str) -> dict[str, VaultVar]:
    folder_id = find_folder(bw, folder)
    if folder_id is None:
        raise SecretsSyncError(f"no Bitwarden folder named {folder!r}; `secrets-sync push` creates it")
    variables: dict[str, VaultVar] = {}
    for item in bw.list_items(folder_id):
        name = item.get("name")
        if not isinstance(name, str):
            raise BwError("unexpected item in `bw list items` output")
        label = printable(name)
        if item.get("organizationId"):
            err(f"warning: item {label!r} belongs to an organization; ignored (keep these items in your personal vault)")
            continue
        fields = item.get("fields") or []
        if not isinstance(fields, list):
            raise BwError(f"item {label!r}: unexpected fields format")
        machines_raw = [f.get("value") for f in fields if isinstance(f, dict) and f.get("name") == MACHINES_FIELD]
        if not machines_raw:
            err(f"warning: item {label!r} has no {MACHINES_FIELD} field; ignored until it has one")
            continue
        machines = parse_machines(machines_raw[0], label)
        for f in fields:
            if not isinstance(f, dict) or f.get("name") == MACHINES_FIELD:
                continue
            var, value, ftype = f.get("name"), f.get("value"), f.get("type")
            if not isinstance(var, str) or not NAME_RE.match(var):
                raise SecretsSyncError(f"item {label!r} has a field whose name is not a valid variable name")
            if is_denied_name(var):
                raise SecretsSyncError(f"item {label!r} sets {var}, which secrets-sync refuses to manage")
            if ftype not in (0, 1):
                raise SecretsSyncError(f"item {label!r}: field {var} must be a hidden (or text) field")
            if value is None:
                err(f"warning: item {label!r}: field {var} is empty; skipped")
                continue
            if not isinstance(value, str):
                raise BwError(f"item {label!r}: field {var} has an unexpected value type")
            REDACT.add(value)
            if ftype == 0:
                err(f"warning: item {label!r}: field {var} is a text field; make it hidden in Bitwarden")
            check_value(var, value)
            if var in variables:
                raise SecretsSyncError(
                    f"{var} is defined in both {variables[var].item!r} and {label!r}; keep one"
                )
            variables[var] = VaultVar(var, value, label, machines)
    return variables


