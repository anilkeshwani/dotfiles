def ensure_safe_dir(path: Path) -> None:
    st = os.stat(path)
    if st.st_uid not in (os.getuid(), 0):
        raise SecretsSyncError(f"{path} is not owned by you; refusing to write there")
    if st.st_mode & 0o022:
        raise SecretsSyncError(f"{path} is writable by group or others; refusing to write there")


def ensure_private_dir(path: Path) -> None:
    path.mkdir(mode=0o700, parents=True, exist_ok=True)
    st = os.lstat(path)
    if stat.S_ISLNK(st.st_mode) or not stat.S_ISDIR(st.st_mode):
        raise SecretsSyncError(f"{path} must be a directory, not a symlink")
    if st.st_uid != os.getuid():
        raise SecretsSyncError(f"{path} is not owned by you")
    if stat.S_IMODE(st.st_mode) != 0o700:
        os.chmod(path, 0o700)
        err(f"warning: tightened {path} to mode 700")


@dataclass
class ExistingFile:
    data: bytes
    identity: tuple[int, int, int, int]  # dev, inode, size, mtime_ns


def read_target(path: Path) -> ExistingFile | None:
    try:
        st = os.lstat(path)
    except FileNotFoundError:
        return None
    if stat.S_ISLNK(st.st_mode):
        raise SecretsSyncError(f"{path} is a symlink; refusing to read or write through it")
    if not stat.S_ISREG(st.st_mode):
        raise SecretsSyncError(f"{path} is not a regular file")
    if st.st_uid != os.getuid():
        raise SecretsSyncError(f"{path} is not owned by you")
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
    try:
        fst = os.fstat(fd)
        chunks = []
        while chunk := os.read(fd, 65536):
            chunks.append(chunk)
    finally:
        os.close(fd)
    if stat.S_IMODE(fst.st_mode) & 0o077:
        err(f"warning: {path} was readable by others (mode {stat.S_IMODE(fst.st_mode):o}); the new file is 600")
    return ExistingFile(b"".join(chunks), (fst.st_dev, fst.st_ino, fst.st_size, fst.st_mtime_ns))


def file_identity(path: Path) -> tuple[int, int, int, int] | None:
    try:
        st = os.lstat(path)
    except FileNotFoundError:
        return None
    return (st.st_dev, st.st_ino, st.st_size, st.st_mtime_ns)


def write_private_file(path: Path, data: bytes) -> None:
    """Write data to path atomically. The temp file is created mode 600 with O_EXCL and
    O_NOFOLLOW in the target's directory before any byte is written, then renamed over the
    target. rename replaces a symlink at the target rather than following it."""
    tmp = path.with_name(f".{path.name}.secrets-sync-{secrets.token_hex(8)}")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC, 0o600)
    try:
        try:
            os.fchmod(fd, 0o600)
            view = memoryview(data)
            while view:
                view = view[os.write(fd, view):]
            os.fsync(fd)
        finally:
            os.close(fd)
        os.replace(tmp, path)
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(tmp)
        raise
    dir_fd = os.open(path.parent, os.O_RDONLY)
    try:
        with contextlib.suppress(OSError):
            os.fsync(dir_fd)
    finally:
        os.close(dir_fd)


def backup_and_prune(paths: Paths, data: bytes, keep: int) -> Path:
    ensure_private_dir(paths.state)
    ensure_private_dir(paths.backups)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S.%fZ")
    target = paths.backups / f"secrets.{stamp}"
    write_private_file(target, data)
    backups = sorted(p for p in paths.backups.iterdir() if p.name.startswith("secrets.") and p.is_file())
    for old in backups[:-keep]:
        old.unlink()
    return target


